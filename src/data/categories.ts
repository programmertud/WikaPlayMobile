export function getAllCategories(): LearningCategory[] {
  return LEARNING_CATEGORIES;
}

export function getCategoryBySlug(slug?: string): LearningCategory {
  if (!slug) return LEARNING_CATEGORIES[0];
  const found = LEARNING_CATEGORIES.find(
    (c) => c.slug === slug || c.id === slug || c.name.toLowerCase() === slug.toLowerCase()
  );
  return found || LEARNING_CATEGORIES[0];
}

export function getCategoryVocabulary(slug?: string): VocabularyItem[] {
  return getCategoryBySlug(slug).items;
}

export function getRandomVocabularyChoices(
  slug: string,
  correctItem: VocabularyItem,
  count = 4
): VocabularyItem[] {
  const allItems = getCategoryVocabulary(slug);
  const others = allItems.filter((i) => i.id !== correctItem.id);
  const shuffled = [...others].sort(() => 0.5 - Math.random()).slice(0, count - 1);
  const choices = [correctItem, ...shuffled].sort(() => 0.5 - Math.random());
  return choices;
}
