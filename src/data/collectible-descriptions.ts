/**
 * Returns the customized description text for a collectible,
 * checking by Filipino name, English name, and slug keys.
 * If not found in the custom dictionary, falls back to item.description or a friendly default.
 */
export function getCollectibleDescription(item?: {
  filipino_name?: string;
  name?: string;
  slug?: string;
  description?: string | null;
} | null): string {
  if (!item) return '';

  const normalize = (str?: string) =>
    (str || '')
      .toLowerCase()
      .trim()
      .replace(/^hayop-|^prutas-|^gulay-|^kulay-|^katawan-|^hugis-|^bilang-|^pagbati-/, '')
      .replace(/^cat-/, '')
      .replace(/[._]/g, '-')
      .trim();

  const candidates = [
    (item.filipino_name || '').toLowerCase().trim(),
    normalize(item.slug),
    normalize(item.filipino_name),
    (item.name || '').toLowerCase().trim(),
    (item.slug || '').toLowerCase().trim(),
  ];

  for (const key of candidates) {
    if (key && COLLECTIBLE_DESCRIPTIONS[key]) {
      return COLLECTIBLE_DESCRIPTIONS[key];
    }
  }

  // If item already has a description, return it
  if (item.description && item.description.trim().length > 0) {
    return item.description;
  }

  return 'Isang natatanging kolektible mula sa WikaPlay!';
}
